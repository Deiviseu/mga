const dict: Record<Lang, Dict> = { pt, en, es };
export type UIKey = keyof typeof pt;

export function useT(lang: Lang) {
  return (key: UIKey): string => dict[lang][key];
}

/** Para objetos de conteúdo {pt,en,es}: retorna o idioma pedido com fallback PT. */
export function tr(v: unknown, lang: Lang): string {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  const o = v as Partial<Record<Lang, string>>;
  return o[lang] ?? o.pt ?? '';
}
